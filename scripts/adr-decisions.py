#!/usr/bin/env python3
"""Write .repowise/decisions.yaml from the ADRs in docs/adr.

Repowise reads accepted decisions from the tracked file
.repowise/decisions.yaml (format version 1). Its command
`repowise decision import` makes its store agree with the file. This script
makes the file from the ADRs, so that the ADRs stay the one source of the
decisions and the file is only a copy of them.

One ADR gives one entry:

- id: "adr-NNNN".
- title: "ADR N: " and the title of the ADR.
- decision: the "Decision" section. When the status line of the ADR tells
  about later changes, the entry gets one more sentence with that text.
  Repowise has no relation for a change in part, so the sentence keeps the
  ADR numbers.
- reason: the start of the "Context" section, at most REASON_MAX characters.
- scope: the repository paths that the ADR names in code spans and that
  exist in the repository. When the ADR names no such path, the scope is
  the ADR file.
- currency: "superseded" when the status line starts with "superseded by
  ADR N", with superseded_by set to that ADR. Else "active".
- accepted_at: the date of the status line.
- accepted_artifact and evidence: the ADR file.

The output does not contain commit hashes. A pull request that adds an ADR
cannot know the hash of the commit that adds the ADR to main, because a
squash merge makes a new commit. A hash in the file would make the check
fail on main after each merge of an ADR.

The output depends only on the ADR files and on which named paths exist in
the tree, so that the check gives the same result on each machine and in a
shallow clone. When a change removes a path that an ADR names, the check
fails until `make adr-decisions` runs again.

Usage:
    adr-decisions.py             write .repowise/decisions.yaml
    adr-decisions.py --check     fail when the file differs from a new output
    adr-decisions.py --selftest

Standard library only.
"""

import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
ADR_DIR = ROOT / "docs" / "adr"
OUT = ROOT / ".repowise" / "decisions.yaml"

# The format version of the file that Repowise reads.
MANIFEST_VERSION = 1
# Repowise stores an id in 32 characters.
ID_MAX = 32
REASON_MAX = 600
# An ADR file is small. A larger file is not an ADR of this repository.
FILE_MAX = 1 << 20

HEADER = (
    "# Accepted architectural decisions for Repowise, made from docs/adr.\n"
    "#\n"
    "# Do not edit this file. Change the ADR and run `make adr-decisions`.\n"
    "# `make docs-lint` fails when this file differs from a new output.\n"
)

# The generated index of the ADRs. It is not an ADR, so it is not a decision.
INDEX_NAME = "INDEX.md"
FILE_NAME = re.compile(r"^(\d{4})-[a-z0-9-]+\.md$")
TITLE = re.compile(r"^# (\d+)\. (.+)$")
DATE = re.compile(r"\b(\d{4}-\d{2}-\d{2})\b")
WHOLE_SUPERSEDED = re.compile(r"^superseded by ADR (\d+)\b", re.IGNORECASE)
# A later change that the status line names: superseded in part, amended,
# extended and the like. The sentence goes into the decision text.
CHANGE = re.compile(
    r"supersed|amend|extend|narrow|chang|refine|replac|added by|decided by|"
    r"kept by|ordered by|answered by|adds to",
    re.IGNORECASE,
)
# A part of the ADR is superseded, or the ADR supersedes a part of another.
PARTIAL = re.compile(r"supersed", re.IGNORECASE)
CODE_SPAN = re.compile(r"`([^`\n]+)`")
LINK = re.compile(r"\[([^\]]+)\]\([^)]*\)")
# A path in the repository: a top directory from the allowlist, then path
# characters only. A placeholder such as `api/<tool>/` does not match.
PATH = re.compile(
    r"^(?:\.github|clients|cmd|deploy|docs|e2e|internal|load|pkg|scripts)"
    r"(?:/[A-Za-z0-9._-]+)+/?$"
)
ROOT_FILES = frozenset(
    {
        ".golangci.yml",
        ".trivyignore",
        "CLAUDE.md",
        "CONTRIBUTING.md",
        "GLOSSARY.md",
        "Makefile",
        "README.md",
        "SECURITY.md",
        "go.mod",
        "go.sum",
    }
)
# Links to other ADRs and RFCs are not code that the decision governs.
NOT_SCOPE = ("docs/adr/", "docs/rfc/")


class ADRError(Exception):
    """An ADR file does not have the form that this script reads."""


def sections(lines):
    """Map each "## " heading to the lines below it."""
    out = {}
    name = None
    for line in lines:
        if line.startswith("## "):
            name = line[3:].strip()
            out.setdefault(name, [])
            continue
        if name is not None:
            out[name].append(line)
    return out


def paragraphs(lines):
    """Join the wrapped lines of each paragraph with one space."""
    out = []
    cur = []
    for line in lines:
        if line.strip():
            cur.append(line.strip())
        elif cur:
            out.append(" ".join(cur))
            cur = []
    if cur:
        out.append(" ".join(cur))
    return out


def plain(text):
    """Replace each Markdown link with its text."""
    return LINK.sub(r"\1", text)


def shorten(text, limit):
    """Cut text at the last sentence end before limit, or at a word."""
    if len(text) <= limit:
        return text
    cut = text[:limit]
    end = cut.rfind(". ")
    if end >= limit // 3:
        return cut[: end + 1]
    space = cut.rfind(" ")
    return (cut[:space] if space > 0 else cut).rstrip(",;:") + " ..."


def reason(context_lines):
    """The start of the Context section, at most REASON_MAX characters."""
    text = ""
    for para in paragraphs(context_lines):
        para = plain(para)
        text = para if not text else text + " " + para
        if len(text) >= REASON_MAX // 3:
            break
    return shorten(text, REASON_MAX)


def decision_text(decision_lines):
    """The Decision section, with each paragraph or list item on one line."""
    out = []
    cur = []
    for line in decision_lines:
        stripped = line.strip()
        starts_item = bool(re.match(r"^(?:[-*] |\d+\. )", stripped)) and not line.startswith("  ")
        if not stripped or starts_item or stripped.startswith("#") or stripped.startswith("|"):
            if cur:
                out.append(" ".join(cur))
                cur = []
            if stripped.startswith("|") or stripped.startswith("#"):
                out.append(stripped)
                continue
        if stripped:
            cur.append(stripped)
    if cur:
        out.append(" ".join(cur))
    return "\n".join(plain(p) for p in out)


def scope(text):
    """The repository paths that the ADR names in code spans, sorted."""
    found = set()
    for span in CODE_SPAN.findall(text):
        token = span.strip()
        if token.endswith("/..."):
            token = token[: -len("/...")]
        if token in ROOT_FILES and (ROOT / token).exists():
            found.add(token)
            continue
        if not PATH.match(token) or ".." in token.split("/"):
            continue
        token = token.rstrip("/")
        if token.startswith(NOT_SCOPE):
            continue
        # An ADR can name a path of another project, for example of the
        # Pulumi CLI. A path that this repository does not hold is not scope.
        if not (ROOT / token).exists():
            continue
        found.add(token)
    return sorted(found)


def parse(name, text):
    """Make the entry of one ADR. Raise ADRError when the ADR has no such form."""
    match = FILE_NAME.match(name)
    if not match:
        raise ADRError(f"{name}: the file name is not NNNN-name.md")
    lines = text.splitlines()
    if not lines:
        raise ADRError(f"{name}: the file is empty")
    title = TITLE.match(lines[0])
    if not title:
        raise ADRError(f"{name}: line 1 is not '# N. Title'")
    number = int(title.group(1))
    if number != int(match.group(1)):
        raise ADRError(f"{name}: the title number {number} is not the file number")
    status = next((ln[len("Status:") :].strip() for ln in lines[:6] if ln.startswith("Status:")), None)
    if not status:
        raise ADRError(f"{name}: no 'Status:' line in the first 6 lines")
    date = DATE.search(status)
    if not date:
        raise ADRError(f"{name}: the status line has no date")
    body = sections(lines)
    for need in ("Context", "Decision"):
        if not "".join(body.get(need, [])).strip():
            raise ADRError(f"{name}: the section '## {need}' is missing or empty")

    path = f"docs/adr/{name}"
    entry = {
        "id": f"adr-{number:04d}",
        "title": f"ADR {number}: {title.group(2).strip()}",
        "decision": decision_text(body["Decision"]),
        "reason": reason(body["Context"]),
        "scope": scope(text) or [path],
        "currency": "active",
        "source": "adr",
        "accepted_at": date.group(1),
        "accepted_artifact": path,
        "evidence": [path],
        "superseded_by": "",
        "partial": False,
    }
    whole = WHOLE_SUPERSEDED.match(status)
    if whole:
        entry["currency"] = "superseded"
        entry["superseded_by"] = f"adr-{int(whole.group(1)):04d}"
    # The status after the date tells about later changes.
    rest = status[date.end() :].lstrip(" ·.").strip()
    if whole:
        rest = status
    if rest and CHANGE.search(rest):
        note = plain(rest).rstrip(".")
        entry["decision"] += f"\n\nLater changes, from the status line of ADR {number}: {note}."
        entry["partial"] = not whole and bool(PARTIAL.search(rest))
    if len(entry["id"]) > ID_MAX:
        raise ADRError(f"{name}: the id {entry['id']} is longer than {ID_MAX} characters")
    return entry


def scalar(value):
    """A YAML double-quoted scalar. JSON string escapes are valid YAML escapes."""
    return json.dumps(value, ensure_ascii=False)


def render(entries):
    """The file text. The order of the entries and the keys is fixed."""
    out = [HEADER, f"version: {MANIFEST_VERSION}\n", "decisions:\n"]
    for e in sorted(entries, key=lambda e: e["id"]):
        out.append(f"- id: {scalar(e['id'])}\n")
        for key in ("title", "decision", "reason"):
            out.append(f"  {key}: {scalar(e[key])}\n")
        out.append("  scope:\n")
        out.extend(f"  - {scalar(s)}\n" for s in sorted(e["scope"]))
        for key in ("currency", "source", "accepted_at", "accepted_artifact"):
            out.append(f"  {key}: {scalar(e[key])}\n")
        out.append("  evidence:\n")
        out.extend(f"  - {scalar(s)}\n" for s in sorted(e["evidence"]))
        if e["superseded_by"]:
            out.append(f"  superseded_by: {scalar(e['superseded_by'])}\n")
    return "".join(out)


def load(adr_dir):
    entries = []
    ids = {}
    for path in sorted(adr_dir.iterdir()):
        if path.suffix != ".md" or path.name == INDEX_NAME:
            continue
        # Do not follow a link out of the ADR directory.
        if path.is_symlink() or not path.is_file():
            raise ADRError(f"{path.name}: not a regular file")
        if path.stat().st_size > FILE_MAX:
            raise ADRError(f"{path.name}: larger than {FILE_MAX} bytes")
        entry = parse(path.name, path.read_text(encoding="utf-8"))
        if entry["id"] in ids:
            raise ADRError(f"{path.name}: the id {entry['id']} is also the id of {ids[entry['id']]}")
        ids[entry["id"]] = path.name
        entries.append(entry)
    for e in entries:
        if e["superseded_by"] and e["superseded_by"] not in ids:
            raise ADRError(f"{e['id']}: superseded by {e['superseded_by']}, which is not an ADR")
    return entries


def counts(entries):
    superseded = sum(1 for e in entries if e["currency"] == "superseded")
    notes = sum(1 for e in entries if "\n\nLater changes, from the status line" in e["decision"])
    in_part = sum(1 for e in entries if e["partial"])
    own = sum(1 for e in entries if e["scope"] != [e["accepted_artifact"]])
    return (
        f"{len(entries)} entries, {superseded} superseded in full, "
        f"{notes} with a note of later changes ({in_part} name a supersession in part), "
        f"{own} with paths in scope"
    )


SAMPLE = """# 7. A sample decision

Status: accepted · 2026-10-08. Decision 2 superseded in part by ADR 9. Extended by ADR 10

## Context

Teams need a [sample](x.md). It is short.

## Decision

- Put the code in `pkg/sample/` and `internal/api/<tool>/`.
- Use `Makefile` and `pkg/store/...`, not `docs/adr/0001-x.md`,
  `pkg/backend/httpstate/client/console.go`
  or `../etc/passwd`.

## Consequences

- None.
"""


def selftest():
    e = parse("0007-sample.md", SAMPLE)
    assert e["id"] == "adr-0007", e["id"]
    assert e["title"] == "ADR 7: A sample decision", e["title"]
    # pkg/sample and the Pulumi CLI path do not exist in this repository.
    assert e["scope"] == ["Makefile", "pkg/store"], e["scope"]
    assert e["reason"] == "Teams need a sample. It is short.", e["reason"]
    assert e["currency"] == "active" and e["partial"], e
    assert "superseded in part by ADR 9. Extended by ADR 10." in e["decision"], e["decision"]
    assert e["accepted_at"] == "2026-10-08", e
    whole = SAMPLE.replace("accepted · 2026-10-08. Decision 2", "superseded by ADR 35 · accepted 2026-10-08. Decision 2")
    w = parse("0007-sample.md", whole)
    assert w["currency"] == "superseded" and w["superseded_by"] == "adr-0035", w
    for bad, why in (
        ("# 8. Wrong number\n\nStatus: accepted · 2026-10-08\n", "title number"),
        ("# 7. No status\n\n## Context\n\nx\n\n## Decision\n\ny\n", "Status"),
        ("# 7. No date\n\nStatus: accepted\n", "no date"),
        ("# 7. No decision\n\nStatus: accepted · 2026-10-08\n\n## Context\n\nx\n", "Decision"),
    ):
        try:
            parse("0007-sample.md", bad)
        except ADRError as err:
            assert why in str(err), (why, err)
        else:
            raise AssertionError(f"accepted an ADR without {why}")
    try:
        parse("7-sample.md", SAMPLE)
    except ADRError:
        pass
    else:
        raise AssertionError("accepted a bad file name")
    assert shorten("a" * 50, 10).endswith("...")
    text = render([e, w | {"id": "adr-0035"}])
    assert text.startswith(HEADER) and "version: 1\n" in text
    assert '  superseded_by: "adr-0035"\n' in text
    assert scalar('a "b"\nc\\') == '"a \\"b\\"\\nc\\\\"'
    print("adr-decisions selftest: ok")


def main(argv):
    if argv == ["--selftest"]:
        selftest()
        return 0
    if argv not in ([], ["--check"]):
        print("usage: adr-decisions.py [--check | --selftest]", file=sys.stderr)
        return 2
    try:
        entries = load(ADR_DIR)
    except (ADRError, OSError, UnicodeDecodeError) as err:
        print(f"adr-decisions: {err}", file=sys.stderr)
        return 1
    text = render(entries)
    if argv == ["--check"]:
        current = OUT.read_text(encoding="utf-8") if OUT.is_file() else ""
        if current != text:
            print(
                f"adr-decisions: {OUT.relative_to(ROOT)} is not the output of the ADRs. "
                "Run `make adr-decisions` and commit the file.",
                file=sys.stderr,
            )
            return 1
        print(f"adr-decisions: {OUT.relative_to(ROOT)} is current: {counts(entries)}")
        return 0
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"adr-decisions: wrote {OUT.relative_to(ROOT)}: {counts(entries)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
