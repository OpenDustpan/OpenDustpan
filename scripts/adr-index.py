#!/usr/bin/env python3
"""Check the change links between the ADRs, and write docs/adr/INDEX.md.

A change link says that a later ADR changes an earlier ADR. The link has two
copies, one in each ADR:

- The later ADR has a "Changes:" list below its status line. Each item names
  the earlier ADR, for example "- Supersedes ADR 4 decisions 1 and 2."
- The earlier ADR has a "Changed by:" list below its status line. Each item
  names the later ADR, for example "- ADR 248 supersedes decisions 1 and 2."

An item has one of three verbs:

- supersedes: the named decisions, or all of the ADR when the item names no
  decision, do not apply now. The later ADR gives the rule.
- changes: the named decisions apply only in part. Read the later ADR too.
- extends: the named decisions apply. The later ADR adds to them.

An item can end with a colon and a short note, for example
"- ADR 210 changes: the route paths."

ADRs older than the first ADR with a "Changes:" list have no such list. Only
the "Changed by:" items in the earlier ADRs record their links. The script
gets that number from --changes-from. Each ADR from that number on must have
a "Changes:" list. An ADR that changes no ADR has the item "- None."

The check fails when:

- an item does not have the form above, or names an ADR that does not exist;
- a "Changes:" item has no matching "Changed by:" item in the earlier ADR;
- a "Changed by:" item names an ADR from --changes-from on, and that ADR has
  no matching "Changes:" item;
- a link goes from an ADR to the same ADR or to a later ADR;
- the status line says "superseded by ADR N" and there is no item
  "- ADR N supersedes." in the "Changed by:" list, or the reverse;
- an ADR from --changes-from on has no "Changes:" list;
- docs/adr/INDEX.md differs from a new output (--check only).

INDEX.md has one line for each ADR: the number, the title, the status, the
ADRs that it changes, the ADRs that change it, and the ADRs that give the
current rule. It shows each link in both directions, also for the older ADRs
that have no "Changes:" list.

Usage:
    adr-index.py --changes-from N            write docs/adr/INDEX.md
    adr-index.py --changes-from N --check    fail when a link or INDEX.md is wrong
    adr-index.py --selftest

Standard library only.
"""

import pathlib
import re
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
ADR_DIR = ROOT / "docs" / "adr"
INDEX_NAME = "INDEX.md"
# An ADR file is small. A larger file is not an ADR of this repository.
FILE_MAX = 1 << 20

FILE_NAME = re.compile(r"^(\d{4})-[a-z0-9-]+\.md$")
TITLE = re.compile(r"^# (\d+)\. (.+)$")
STATUS = re.compile(r"^Status: (.+)$")
WHOLE_SUPERSEDED = re.compile(r"^superseded by ADR (\d+)\b", re.IGNORECASE)

VERBS = ("supersedes", "changes", "extends")
DECISIONS = r"(?: (?:decision (?P<one>\d+)|decisions (?P<many>(?:\d+, )*\d+ and \d+)))?"
NOTE = r"(?:: (?P<note>\S.*?))?"
CHANGES_ITEM = re.compile(
    r"^(?P<verb>Supersedes|Changes|Extends) ADR (?P<adr>\d+)" + DECISIONS + NOTE + r"\.$"
)
CHANGED_BY_ITEM = re.compile(
    r"^ADR (?P<adr>\d+) (?P<verb>supersedes|changes|extends)" + DECISIONS + NOTE + r"\.$"
)
NONE_ITEM = "None."
LABEL_CHANGES = "Changes:"
LABEL_CHANGED_BY = "Changed by:"

HEADER = """\
# ADR index

Do not edit this file. Change the ADRs and run `make adr-index`.
`make docs-lint` fails when this file differs from a new output.

One line for each ADR. "Changes" names the earlier ADRs that this ADR
changes. "Changed by" names the later ADRs that change this ADR. "Current
rule" names the ADRs to read for the rule that applies now. Each link shows
the decisions that it changes, when the ADRs name them.

The verbs: "supersedes" means that the named part does not apply now.
"changes" means that the named part applies only in part. "extends" means
that the named part applies, and the later ADR adds to it.

| ADR | Title | Status | Changes | Changed by | Current rule |
| --- | --- | --- | --- | --- | --- |
"""


class ADRError(Exception):
    """An ADR or a change link does not have the form that this script reads."""


class ADR:
    """The parts of one ADR that the index uses."""

    def __init__(self, number, name, title, status):
        self.number = number
        self.name = name
        self.title = title
        self.status = status
        # None when the ADR has no "Changes:" list.
        self.changes = None
        self.changed_by = None


def parse_decisions(match):
    """Return the decision numbers of an item as a tuple, ascending."""
    if match.group("one"):
        return (int(match.group("one")),)
    many = match.group("many")
    if not many:
        return ()
    head, last = many.rsplit(" and ", 1)
    numbers = [int(n) for n in head.split(", ")] + [int(last)]
    if numbers != sorted(set(numbers)):
        raise ValueError("the decision numbers are not in ascending order")
    return tuple(numbers)


def format_decisions(decisions):
    if not decisions:
        return ""
    if len(decisions) == 1:
        return f" decision {decisions[0]}"
    head = ", ".join(str(n) for n in decisions[:-1])
    return f" decisions {head} and {decisions[-1]}"


def status_area(lines):
    """Return the lines from the status line to the first "## " heading."""
    out = []
    for line in lines[3:]:
        if line.startswith("## "):
            break
        out.append(line)
    return out


def read_lists(name, area):
    """Return the items of the "Changes:" and "Changed by:" lists.

    Each value is None when the list is not there. An item can continue on
    lines that start with two spaces.
    """
    lists = {LABEL_CHANGES: None, LABEL_CHANGED_BY: None}
    index = 0
    while index < len(area):
        line = area[index]
        if line not in lists:
            index += 1
            continue
        if lists[line] is not None:
            raise ADRError(f"{name}: two {line!r} lists")
        label = line
        items = []
        index += 1
        while index < len(area) and not area[index].strip():
            index += 1
        while index < len(area):
            line = area[index]
            if line.startswith("- "):
                items.append(line[2:].strip())
            elif line.startswith("  ") and line.strip() and items:
                items[-1] += " " + line.strip()
            else:
                break
            index += 1
        if not items:
            raise ADRError(f"{name}: the {label!r} list has no items")
        lists[label] = items
    return lists[LABEL_CHANGES], lists[LABEL_CHANGED_BY]


def parse_item(name, label, text):
    """Return (adr, verb, decisions, note) for one item."""
    pattern = CHANGES_ITEM if label == LABEL_CHANGES else CHANGED_BY_ITEM
    match = pattern.match(text)
    if not match:
        raise ADRError(f"{name}: the {label!r} item {text!r} does not have the form of an item")
    try:
        decisions = parse_decisions(match)
    except ValueError as err:
        raise ADRError(f"{name}: the {label!r} item {text!r}: {err}") from None
    return int(match.group("adr")), match.group("verb").lower(), decisions, match.group("note")


def parse(name, text):
    match = FILE_NAME.match(name)
    if not match:
        raise ADRError(f"{name}: the file name is not NNNN-name.md")
    lines = text.splitlines()
    if len(lines) < 3:
        raise ADRError(f"{name}: the file has less than 3 lines")
    title = TITLE.match(lines[0])
    if not title or int(title.group(1)) != int(match.group(1)):
        raise ADRError(f"{name}: line 1 is not '# N. Title' with the number of the file")
    status = STATUS.match(lines[2])
    if not status:
        raise ADRError(f"{name}: line 3 is not 'Status: ...'")
    # The state is the text before the first " · " and before the first ". ".
    state = status.group(1).split(" · ")[0].split(". ")[0].strip()
    adr = ADR(int(match.group(1)), name, title.group(2).strip(), state)
    changes, changed_by = read_lists(name, status_area(lines))
    if changes is not None:
        if changes == [NONE_ITEM]:
            adr.changes = []
        else:
            adr.changes = [parse_item(name, LABEL_CHANGES, t) for t in changes]
    if changed_by is not None:
        adr.changed_by = [parse_item(name, LABEL_CHANGED_BY, t) for t in changed_by]
    return adr


def load(adr_dir):
    adrs = {}
    for path in sorted(adr_dir.iterdir()):
        if path.suffix != ".md" or path.name == INDEX_NAME:
            continue
        # Do not follow a link out of the ADR directory.
        if path.is_symlink() or not path.is_file():
            raise ADRError(f"{path.name}: not a regular file")
        if path.stat().st_size > FILE_MAX:
            raise ADRError(f"{path.name}: larger than {FILE_MAX} bytes")
        adr = parse(path.name, path.read_text(encoding="utf-8"))
        if adr.number in adrs:
            raise ADRError(f"{path.name}: ADR {adr.number} has two files")
        adrs[adr.number] = adr
    return adrs


def links(adrs, changes_from):
    """Check the links and return them as a set of (later, earlier, verb, decisions)."""
    errors = []
    forward = {}
    reverse = {}
    for adr in adrs.values():
        if adr.number >= changes_from and adr.changes is None:
            errors.append(f"{adr.name}: the ADR has no {LABEL_CHANGES!r} list")
        for target, verb, decisions, _ in adr.changes or []:
            key = (adr.number, target, verb, decisions)
            if key in forward:
                errors.append(f"{adr.name}: two {LABEL_CHANGES!r} items for ADR {target}")
            forward[key] = adr.name
        for source, verb, decisions, _ in adr.changed_by or []:
            key = (source, adr.number, verb, decisions)
            if key in reverse:
                errors.append(f"{adr.name}: two {LABEL_CHANGED_BY!r} items for ADR {source}")
            reverse[key] = adr.name
    for later, earlier, verb, decisions in sorted(forward):
        name = adrs[later].name
        if earlier not in adrs:
            errors.append(f"{name}: ADR {earlier} does not exist")
            continue
        if earlier >= later:
            errors.append(f"{name}: a link to ADR {earlier}, which is not an earlier ADR")
        if (later, earlier, verb, decisions) not in reverse:
            errors.append(
                f"{name}: the item '{verb} ADR {earlier}{format_decisions(decisions)}' has no "
                f"item 'ADR {later} {verb}{format_decisions(decisions)}' in "
                f"the {LABEL_CHANGED_BY!r} list of {adrs[earlier].name}"
            )
    for later, earlier, verb, decisions in sorted(reverse):
        name = adrs[earlier].name
        if later not in adrs:
            errors.append(f"{name}: ADR {later} does not exist")
            continue
        if later <= earlier:
            errors.append(f"{name}: a link from ADR {later}, which is not a later ADR")
        if later >= changes_from and (later, earlier, verb, decisions) not in forward:
            errors.append(
                f"{name}: the item 'ADR {later} {verb}{format_decisions(decisions)}' has no "
                f"item '{verb} ADR {earlier}{format_decisions(decisions)}' in "
                f"the {LABEL_CHANGES!r} list of {adrs[later].name}"
            )
    all_links = set(forward) | set(reverse)
    for adr in adrs.values():
        match = WHOLE_SUPERSEDED.match(adr.status)
        whole = sorted(k[0] for k in all_links if k[1] == adr.number and k[2] == "supersedes" and not k[3])
        if match and [int(match.group(1))] != whole:
            errors.append(
                f"{adr.name}: the status says superseded by ADR {match.group(1)}, and the "
                f"{LABEL_CHANGED_BY!r} list does not have exactly one item "
                f"'ADR {match.group(1)} supersedes.'"
            )
        if not match and whole:
            errors.append(
                f"{adr.name}: ADR {whole[0]} supersedes all of the ADR, and the status "
                f"does not say 'superseded by ADR {whole[0]}'"
            )
    if errors:
        raise ADRError("\n".join(errors))
    return all_links


def current(adrs, all_links, number, seen=()):
    """Return the ADR that holds the rule of ADR number after whole supersessions."""
    if number in seen:
        raise ADRError(f"a loop of whole supersessions through ADR {number}")
    for later, earlier, verb, decisions in all_links:
        if earlier == number and verb == "supersedes" and not decisions:
            return current(adrs, all_links, later, seen + (number,))
    return number


def cell(text):
    return text.replace("|", "\\|") if text else "-"


def render(adrs, all_links):
    out = [HEADER]
    for number in sorted(adrs):
        adr = adrs[number]
        changes = sorted((k for k in all_links if k[0] == number), key=lambda k: (k[1], k[2], k[3]))
        changed_by = sorted((k for k in all_links if k[1] == number), key=lambda k: (k[0], k[2], k[3]))
        changes_text = "; ".join(f"{v} ADR {e}{format_decisions(d)}" for _, e, v, d in changes)
        changed_by_text = "; ".join(f"ADR {l} {v}{format_decisions(d)}" for l, _, v, d in changed_by)
        holder = current(adrs, all_links, number)
        if holder != number:
            rule = f"ADR {holder}"
        else:
            readers = sorted({current(adrs, all_links, k[0]) for k in changed_by})
            rule = "this ADR"
            if readers:
                rule += ", with ADR " + ", ".join(str(n) for n in readers)
        out.append(
            f"| [{number}]({adr.name}) | {cell(adr.title)} | {cell(adr.status)} | "
            f"{cell(changes_text)} | {cell(changed_by_text)} | {rule} |\n"
        )
    return "".join(out)


def build(adr_dir, changes_from):
    adrs = load(adr_dir)
    return render(adrs, links(adrs, changes_from))


def index_is_current(adr_dir, changes_from):
    """Return True when INDEX.md in adr_dir is the same as a new output."""
    text = build(adr_dir, changes_from)
    index = adr_dir / INDEX_NAME
    if index.is_symlink() or not index.is_file():
        return False
    return index.read_text(encoding="utf-8") == text


def selftest():
    def adr(number, title, status="accepted · 2026-10-31", area=""):
        return f"# {number}. {title}\n\nStatus: {status}\n{area}\n## Context\n\nText.\n"

    def run(files, changes_from=3):
        with tempfile.TemporaryDirectory() as tmp:
            path = pathlib.Path(tmp)
            for name, text in files.items():
                (path / name).write_text(text, encoding="utf-8")
            return build(path, changes_from)

    def fails(files, part, changes_from=3):
        try:
            run(files, changes_from)
        except ADRError as err:
            assert part in str(err), f"want {part!r} in {err}"
            return
        raise AssertionError(f"no error, want {part!r}")

    good = {
        "0001-one.md": adr(
            1,
            "One",
            "superseded by ADR 2 · accepted 2026-10-01",
            "\nChanged by:\n\n- ADR 2 supersedes.\n",
        ),
        "0002-two.md": adr(
            2,
            "Two | pipe",
            area="\nChanged by:\n\n- ADR 3 changes decisions 1, 4 and 9: the route\n  paths.\n"
            "- ADR 4 extends decision 2.\n",
        ),
        "0003-three.md": adr(3, "Three", area="\nChanges:\n\n- Changes ADR 2 decisions 1, 4 and 9.\n"),
        "0004-four.md": adr(4, "Four", area="\nChanges:\n\n- Extends ADR 2 decision 2: more.\n"),
        "0005-five.md": adr(5, "Five", area="\nChanges:\n\n- None.\n"),
        INDEX_NAME: "ignored\n",
    }
    text = run(good)
    lines = text.splitlines()
    rows = [line for line in lines if line.startswith("| [")]
    assert len(rows) == 5, rows
    assert rows[0] == (
        "| [1](0001-one.md) | One | superseded by ADR 2 | - | ADR 2 supersedes | ADR 2 |"
    ), rows[0]
    assert rows[1] == (
        "| [2](0002-two.md) | Two \\| pipe | accepted | supersedes ADR 1 | "
        "ADR 3 changes decisions 1, 4 and 9; ADR 4 extends decision 2 | this ADR, with ADR 3, 4 |"
    ), rows[1]
    assert rows[4].endswith("| - | - | this ADR |"), rows[4]

    bad = dict(good)
    bad["0004-four.md"] = adr(4, "Four", area="\nChanges:\n\n- Extends ADR 2 decision 3.\n")
    fails(bad, "has no item 'ADR 4 extends decision 3'")

    bad = dict(good)
    bad["0005-five.md"] = adr(5, "Five")
    fails(bad, "0005-five.md: the ADR has no 'Changes:' list")

    bad = dict(good)
    bad["0002-two.md"] = adr(2, "Two", area="\nChanged by:\n\n- ADR 3 changes decisions 1, 4 and 9.\n")
    fails(bad, "has no item 'ADR 4 extends decision 2'")

    bad = dict(good)
    bad["0001-one.md"] = adr(1, "One", "superseded by ADR 2 · accepted 2026-10-01")
    fails(bad, "the status says superseded by ADR 2")

    bad = dict(good)
    bad["0001-one.md"] = adr(1, "One", area="\nChanged by:\n\n- ADR 2 supersedes.\n")
    fails(bad, "does not say 'superseded by ADR 2'")

    bad = dict(good)
    bad["0002-two.md"] = good["0002-two.md"].replace("ADR 4 extends decision 2.", "ADR 4 amends decision 2.")
    fails(bad, "does not have the form of an item")

    bad = dict(good)
    bad["0003-three.md"] = adr(3, "Three", area="\nChanges:\n\n- Changes ADR 2 decisions 4, 1 and 9.\n")
    fails(bad, "not in ascending order")

    bad = dict(good)
    bad["0005-five.md"] = adr(5, "Five", area="\nChanges:\n\n- Changes ADR 7.\n")
    fails(bad, "ADR 7 does not exist")

    bad = dict(good)
    bad["0002-two.md"] = good["0002-two.md"] + "\n"
    bad["0002-two.md"] = bad["0002-two.md"].replace("- ADR 4 extends", "- ADR 1 extends")
    fails(bad, "which is not a later ADR")

    bad = dict(good)
    bad["0006-x.md"] = adr(7, "Seven", area="\nChanges:\n\n- None.\n")
    fails(bad, "with the number of the file")

    bad = dict(good)
    bad["notes.md"] = "x\n"
    fails(bad, "the file name is not NNNN-name.md")

    # A "Changed by:" item from an ADR before --changes-from needs no
    # "Changes:" list in that ADR.
    old = {
        "0001-one.md": adr(1, "One", area="\nChanged by:\n\n- ADR 2 changes decision 1.\n"),
        "0002-two.md": adr(2, "Two"),
    }
    text = run(old, changes_from=5)
    assert "| [2](0002-two.md) | Two | accepted | changes ADR 1 decision 1 | - | this ADR |" in text, text
    fails(old, "has no item 'changes ADR 1 decision 1'", changes_from=2)

    bad = dict(good)
    bad["0003-three.md"] = adr(3, "Three", area="\nChanges:\n\n- Changes ADR 2 decisions 1, 4 and 9.\n- Changes ADR 5.\n")
    bad["0005-five.md"] = adr(5, "Five", area="\nChanges:\n\n- None.\n\nChanged by:\n\n- ADR 3 changes.\n")
    fails(bad, "0003-three.md: a link to ADR 5, which is not an earlier ADR")

    bad = dict(good)
    bad["0002-two.md"] = good["0002-two.md"].replace(
        "- ADR 4 extends decision 2.\n", "- ADR 4 extends decision 2.\n- ADR 4 extends decision 2.\n"
    )
    fails(bad, "0002-two.md: two 'Changed by:' items for ADR 4")

    bad = dict(good)
    bad["0004-four.md"] = adr(
        4, "Four", area="\nChanges:\n\n- Extends ADR 2 decision 2: more.\n- Extends ADR 2 decision 2: again.\n"
    )
    fails(bad, "0004-four.md: two 'Changes:' items for ADR 2")

    # The check of INDEX.md: current, stale and missing.
    with tempfile.TemporaryDirectory() as tmp:
        path = pathlib.Path(tmp)
        for name, content in good.items():
            if name != INDEX_NAME:
                (path / name).write_text(content, encoding="utf-8")
        assert not index_is_current(path, 3), "a missing INDEX.md is current"
        (path / INDEX_NAME).write_text(build(path, 3), encoding="utf-8")
        assert index_is_current(path, 3), "a new INDEX.md is not current"
        (path / INDEX_NAME).write_text(build(path, 3) + "| [9](x.md) | edited |\n", encoding="utf-8")
        assert not index_is_current(path, 3), "an edited INDEX.md is current"
        (path / INDEX_NAME).write_text(build(path, 3), encoding="utf-8")
        (path / "0005-five.md").write_text(adr(5, "Five again", area="\nChanges:\n\n- None.\n"), encoding="utf-8")
        assert not index_is_current(path, 3), "INDEX.md is current after a change of an ADR"

    # The current rule follows a chain of whole supersessions.
    chain = {
        "0001-one.md": adr(1, "One", "superseded by ADR 2", "\nChanged by:\n\n- ADR 2 supersedes.\n"),
        "0002-two.md": adr(2, "Two", "superseded by ADR 3", "\nChanged by:\n\n- ADR 3 supersedes.\n"),
        "0003-three.md": adr(3, "Three", area="\nChanges:\n\n- Supersedes ADR 2.\n"),
    }
    text = run(chain)
    assert "| superseded by ADR 2 | - | ADR 2 supersedes | ADR 3 |" in text, text
    print("adr-index selftest: ok")


def main(argv):
    if argv == ["--selftest"]:
        selftest()
        return 0
    check = "--check" in argv
    rest = [a for a in argv if a != "--check"]
    if len(rest) != 2 or rest[0] != "--changes-from" or not rest[1].isdigit():
        print("usage: adr-index.py --changes-from N [--check] | --selftest", file=sys.stderr)
        return 2
    changes_from = int(rest[1])
    index = ADR_DIR / INDEX_NAME
    try:
        text = build(ADR_DIR, changes_from)
        current = index_is_current(ADR_DIR, changes_from)
    except ADRError as err:
        print(f"adr-index: {err}", file=sys.stderr)
        return 1
    if check:
        if not current:
            print(f"adr-index: {index.relative_to(ROOT)} is not current. Run `make adr-index`.", file=sys.stderr)
            return 1
        print(f"adr-index: {len(text.splitlines()) - HEADER.count(chr(10))} ADRs, the links and the index are correct")
        return 0
    index.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
