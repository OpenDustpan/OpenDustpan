func TestBreakGlassRotate(t *testing.T) {
	t.Parallel()
	t.Run("rotation inserts new credential before ending old", func(t *testing.T) {
		t.Parallel()
		t.Fatal("break-glass rotation not implemented")
	})
	t.Run("unknown id returns not found", func(t *testing.T) {
		t.Parallel()
		t.Fatal("break-glass rotation not implemented")
	})
	t.Run("parallel rotation", func(t *testing.T) {
		t.Parallel()
		t.Fatal("break-glass rotation not implemented")
	})
	t.Run("sweep audit record", func(t *testing.T) {
		t.Parallel()
		t.Fatal("break-glass sweep audit not implemented")
	})
}
