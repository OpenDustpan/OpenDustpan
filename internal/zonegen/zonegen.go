// Package zonegen writes the list of IANA zone names that the preferences
// package accepts. It reads the time zone archive of the Go toolchain, so the
// list does not depend on the zone files of the host.
package zonegen

import (
	"archive/zip"
	"bytes"
	"context"
	"errors"
	"fmt"
	"go/format"
	"os/exec"
	"path/filepath"
	"slices"
	"strings"
)

// ErrNoZones is the error for an archive that holds no zone.
var ErrNoZones = errors.New("zonegen: the archive holds no zone")

// ErrBadName is the error for an archive entry whose name is not a zone name.
var ErrBadName = errors.New("zonegen: the archive holds an entry that is not a zone name")

// ErrTooManyEntries is the error for an archive with more than maxEntries entries.
var ErrTooManyEntries = errors.New("zonegen: the archive holds too many entries")

// ErrNoRoot is the error for a go command that answers an empty GOROOT.
var ErrNoRoot = errors.New("zonegen: GOROOT is empty")

const (
	// maxEntries limits the entries that Generate accepts in one archive; the
	// archive of the toolchain holds about 600.
	maxEntries = 4096
	// maxNameLen is the longest zone name, the same limit as the preferences check.
	maxNameLen = 64
)

// ArchivePath answers the path of the time zone archive of the Go toolchain
// that the go command on PATH uses.
func ArchivePath(ctx context.Context) (string, error) {
	out, err := exec.CommandContext(ctx, "go", "env", "GOROOT").Output()
	if err != nil {
		return "", fmt.Errorf("zonegen: read GOROOT: %w", err)
	}

	root := strings.TrimSpace(string(out))
	if root == "" {
		return "", ErrNoRoot
	}

	return filepath.Join(root, "lib", "time", "zoneinfo.zip"), nil
}

// Generate answers the source of the generated Go file for the zone archive
// archive. The output is the same for the same archive.
func Generate(archive []byte) ([]byte, error) {
	names, err := zoneNames(archive)
	if err != nil {
		return nil, err
	}

	var src bytes.Buffer

	src.WriteString("// Code generated by cmd/zonegen from the time zone archive of the Go toolchain; DO NOT EDIT.\n\n")
	src.WriteString("package preferences\n\n")
	src.WriteString("// knownZone reports whether name is exactly the name of a zone in the time zone\n")
	src.WriteString("// archive of the Go toolchain. The comparison is case-sensitive and reads no file.\n")
	src.WriteString("func knownZone(name string) bool {\n\tswitch name {\n\tcase ")

	for i, name := range names {
		if i > 0 {
			src.WriteString(",\n\t\t")
		}

		fmt.Fprintf(&src, "%q", name)
	}

	src.WriteString(":\n\t\treturn true\n\tdefault:\n\t\treturn false\n\t}\n}\n")

	formatted, err := format.Source(src.Bytes())
	if err != nil {
		return nil, fmt.Errorf("zonegen: format output: %w", err)
	}

	return formatted, nil
}

// zoneNames answers the sorted, unique file names of the archive.
func zoneNames(archive []byte) ([]string, error) {
	reader, err := zip.NewReader(bytes.NewReader(archive), int64(len(archive)))
	if errors.Is(err, zip.ErrInsecurePath) {
		return nil, fmt.Errorf("%w: %w", ErrBadName, err)
	}

	if err != nil {
		return nil, fmt.Errorf("zonegen: open archive: %w", err)
	}

	if len(reader.File) > maxEntries {
		return nil, fmt.Errorf("%w: %d, the limit is %d", ErrTooManyEntries, len(reader.File), maxEntries)
	}

	names := make([]string, 0, len(reader.File))

	for _, entry := range reader.File {
		if strings.HasSuffix(entry.Name, "/") {
			continue
		}

		if !validName(entry.Name) {
			return nil, fmt.Errorf("%w: %q", ErrBadName, entry.Name)
		}

		names = append(names, entry.Name)
	}

	slices.Sort(names)

	names = slices.Compact(names)
	if len(names) == 0 {
		return nil, ErrNoZones
	}

	return names, nil
}

// validName reports whether name has the characters of a zone name. The
// generator refuses any other entry, so a changed archive cannot add a hostile
// name to the list.
func validName(name string) bool {
	if name == "" || len(name) > maxNameLen || strings.HasPrefix(name, "/") || strings.Contains(name, "//") {
		return false
	}

	// The names of the zone of the host and of host-only files are never zones.
	first, _, _ := strings.Cut(name, "/")
	switch strings.ToLower(first) {
	case "local", "localtime", "posixrules", "posix", "right":
		return false
	default:
	}

	for i := range len(name) {
		if !nameByte(name[i]) {
			return false
		}
	}

	return true
}

// nameByte reports whether c can be in a zone name.
func nameByte(c byte) bool {
	return c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || c >= '0' && c <= '9' ||
		c == '/' || c == '_' || c == '+' || c == '-'
}
