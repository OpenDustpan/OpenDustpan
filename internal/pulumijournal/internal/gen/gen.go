// Package gen writes the journal entry types of the pulumijournal package.
//
// It reads a copy of the upstream journal.go file. It stops when the hash of
// the copy is not the pinned hash. It keeps the kind constants and the link
// fields. It maps all other state types to raw JSON. It writes one Go file.
package gen

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"strings"
)

// ErrInputHash reports that the input file is not the pinned upstream copy.
var ErrInputHash = errors.New("gen: input is not the pinned upstream copy")

// Names of the input declarations that the output keeps.
const (
	kindName      = "JournalEntryKind"
	basePatchName = "JournalBaseStatePatch"
	newPatchName  = "JournalNewStatePatch"
	layoutName    = "JournalLayoutItem"
	entryName     = "JournalEntry"
	entriesName   = "JournalEntries"
)

// rawFieldType is the output type for fields that hold raw JSON.
const rawFieldType = "jsontext.Value"

// unknownUpstream names the upstream type when the input type is not a plain name.
const unknownUpstream = "value"

// Generate writes the journal entry file from the upstream input file.
// It returns an error when the input hash is not the pinned hash.
func Generate(input []byte) ([]byte, error) {
	sum := sha256.Sum256(input)
	got := hex.EncodeToString(sum[:])
	if got != InputSHA256 {
		return nil, fmt.Errorf(
			"gen: input hash %s is not the pinned hash %s: %w",
			got,
			InputSHA256,
			ErrInputHash,
		)
	}
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "journal.go", input, parser.ParseComments)
	if err != nil {
		return nil, fmt.Errorf("gen: parse input: %w", err)
	}
	out, err := buildFile(fset, file, input)
	if err != nil {
		return nil, err
	}
	formatted, err := format.Source(out)
	if err != nil {
		return nil, fmt.Errorf("gen: format output: %w", err)
	}
	return formatted, nil
}

// decls holds the input declarations that the output keeps.
type decls struct {
	kind      *ast.GenDecl
	constants *ast.GenDecl
	kindStr   *ast.FuncDecl
	structs   map[string]*ast.GenDecl
}

// structTypeNames lists the structs that the output keeps, in output order.
func structTypeNames() []string {
	return []string{basePatchName, newPatchName, layoutName, entryName, entriesName}
}

// buildFile writes the output file from the parsed input.
func buildFile(fset *token.FileSet, file *ast.File, src []byte) ([]byte, error) {
	found, err := findDecls(file)
	if err != nil {
		return nil, err
	}
	var buf bytes.Buffer
	buf.WriteString(licenseText(src, fset, file))
	buf.WriteString("\n")
	buf.WriteString("// Code generated by the journal generator from apitype/journal.go")
	buf.WriteString(" at commit " + Commit + " (tag " + Tag + "). DO NOT EDIT.\n")
	buf.WriteString("\n")
	buf.WriteString("package pulumijournal\n\n")
	buf.WriteString("import \"encoding/json/jsontext\"\n\n")
	for _, node := range []ast.Node{found.kind, found.constants, found.kindStr} {
		if err := printer.Fprint(&buf, fset, node); err != nil {
			return nil, fmt.Errorf("gen: print declaration: %w", err)
		}
		buf.WriteString("\n\n")
	}
	for _, name := range []string{basePatchName, newPatchName, layoutName, entryName} {
		if err := writeStruct(&buf, found.structs[name]); err != nil {
			return nil, err
		}
		buf.WriteString("\n")
	}
	buf.WriteString("// JournalEntry.String was not generated because its fields are raw JSON.\n\n")
	if err := writeStruct(&buf, found.structs[entriesName]); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// licenseText returns the comment lines before the package clause, verbatim.
func licenseText(src []byte, fset *token.FileSet, file *ast.File) string {
	off := fset.Position(file.Package).Offset
	head := string(src[:off])
	return strings.TrimRight(head, " \t\r\n") + "\n"
}

// findDecls returns the input declarations that the output keeps.
// It returns an error when one of them is missing.
func findDecls(file *ast.File) (*decls, error) {
	found := new(decls)
	found.structs = map[string]*ast.GenDecl{}
	for _, decl := range file.Decls {
		switch node := decl.(type) {
		case *ast.GenDecl:
			rememberGenDecl(found, node)
		case *ast.FuncDecl:
			rememberFuncDecl(found, node)
		default:
		}
	}
	if found.kind == nil || found.constants == nil || found.kindStr == nil {
		return nil, fmt.Errorf("gen: missing JournalEntryKind declaration: %w", ErrInputHash)
	}
	for _, name := range structTypeNames() {
		if found.structs[name] == nil {
			return nil, fmt.Errorf("gen: missing struct %s: %w", name, ErrInputHash)
		}
	}
	return found, nil
}

// rememberGenDecl keeps a type or constant declaration when the output needs it.
func rememberGenDecl(found *decls, node *ast.GenDecl) {
	if len(node.Specs) == 0 {
		return
	}
	if node.Tok == token.TYPE {
		rememberTypeDecl(found, node)
		return
	}
	if node.Tok == token.CONST {
		rememberConstDecl(found, node)
	}
}

// rememberTypeDecl keeps one type declaration when the output needs it.
func rememberTypeDecl(found *decls, node *ast.GenDecl) {
	spec, ok := node.Specs[0].(*ast.TypeSpec)
	if !ok {
		return
	}
	switch spec.Name.Name {
	case kindName:
		found.kind = node
	case basePatchName, newPatchName, layoutName, entryName, entriesName:
		found.structs[spec.Name.Name] = node
	default:
	}
}

// rememberConstDecl keeps the kind constant block of the input.
func rememberConstDecl(found *decls, node *ast.GenDecl) {
	for _, spec := range node.Specs {
		value, ok := spec.(*ast.ValueSpec)
		if !ok || len(value.Names) == 0 {
			continue
		}
		if strings.HasPrefix(value.Names[0].Name, kindName) {
			found.constants = node
			return
		}
	}
}

// rememberFuncDecl keeps the one method with a JournalEntryKind receiver.
// The pinned input holds a single such method, the String method of the kind.
func rememberFuncDecl(found *decls, node *ast.FuncDecl) {
	if node.Recv == nil || len(node.Recv.List) == 0 {
		return
	}
	recv, ok := node.Recv.List[0].Type.(*ast.Ident)
	if !ok {
		return
	}
	if recv.Name == kindName {
		found.kindStr = node
	}
}

// keptType reports whether a field type stays typed in the output.
func keptType(name string) bool {
	switch name {
	case "int", "int64", "bool", "string",
		kindName,
		basePatchName, newPatchName, layoutName,
		entryName, entriesName:
		return true
	default:
		return false
	}
}

// mappedType is the output type of one input field type. Upstream is the
// name of the upstream type when Out holds raw JSON, and empty otherwise.
type mappedType struct {
	Out      string
	Upstream string
}

// mapFieldType maps one input field type to the output type.
func mapFieldType(expr ast.Expr) mappedType {
	switch node := expr.(type) {
	case *ast.Ident:
		if keptType(node.Name) {
			return mappedType{Out: node.Name, Upstream: ""}
		}
		return mappedType{Out: rawFieldType, Upstream: node.Name}
	case *ast.StarExpr:
		base, ok := node.X.(*ast.Ident)
		if !ok {
			return mappedType{Out: rawFieldType, Upstream: unknownUpstream}
		}
		if keptType(base.Name) {
			return mappedType{Out: "*" + base.Name, Upstream: ""}
		}
		return mappedType{Out: rawFieldType, Upstream: base.Name}
	case *ast.ArrayType:
		if node.Len != nil {
			return mappedType{Out: rawFieldType, Upstream: unknownUpstream}
		}
		base, ok := node.Elt.(*ast.Ident)
		if !ok {
			return mappedType{Out: "[]" + rawFieldType, Upstream: unknownUpstream}
		}
		if keptType(base.Name) {
			return mappedType{Out: "[]" + base.Name, Upstream: ""}
		}
		return mappedType{Out: "[]" + rawFieldType, Upstream: base.Name}
	default:
		return mappedType{Out: rawFieldType, Upstream: unknownUpstream}
	}
}

// writeStruct writes one struct with mapped field types. It returns an error
// when decl is not a struct declaration.
func writeStruct(buf *bytes.Buffer, decl *ast.GenDecl) error {
	if decl == nil || len(decl.Specs) == 0 {
		return fmt.Errorf("gen: struct declaration is missing: %w", ErrInputHash)
	}
	spec, ok := decl.Specs[0].(*ast.TypeSpec)
	if !ok {
		return fmt.Errorf("gen: struct declaration is not a type: %w", ErrInputHash)
	}
	body, ok := spec.Type.(*ast.StructType)
	if !ok {
		return fmt.Errorf("gen: %s is not a struct: %w", spec.Name.Name, ErrInputHash)
	}
	writeDocLines(buf, "", decl.Doc)
	buf.WriteString("type " + spec.Name.Name + " struct {\n")
	for _, field := range body.Fields.List {
		writeField(buf, field)
	}
	buf.WriteString("}\n")
	return nil
}

// writeField writes one struct field with its doc comment and mapped type.
func writeField(buf *bytes.Buffer, field *ast.Field) {
	writeDocLines(buf, "\t", field.Doc)
	mapped := mapFieldType(field.Type)
	names := make([]string, 0, len(field.Names))
	for _, name := range field.Names {
		names = append(names, name.Name)
	}
	if mapped.Upstream != "" && len(names) > 0 {
		buf.WriteString("\t// " + names[0] + " is the raw JSON of the upstream " + mapped.Upstream + ".\n")
	}
	tag := ""
	if field.Tag != nil {
		tag = " " + field.Tag.Value
	}
	buf.WriteString("\t" + strings.Join(names, ", ") + " " + mapped.Out + tag + "\n")
	writeDocLines(buf, "\t", field.Comment)
}

// writeDocLines writes one comment group verbatim, indented by prefix.
func writeDocLines(buf *bytes.Buffer, prefix string, group *ast.CommentGroup) {
	if group == nil {
		return
	}
	for _, comment := range group.List {
		buf.WriteString(prefix + comment.Text + "\n")
	}
}
