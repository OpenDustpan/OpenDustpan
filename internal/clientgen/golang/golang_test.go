// TestRenderTypeList checks that a type list becomes a named type that holds
// the JSON types of the list, with the name of the field, and that the
// description of a field is the doc comment of the field, in place of the
// description of its type.
func TestRenderTypeList(t *testing.T) {
	t.Parallel()

	value := model.Field{
		Name: "value", Type: unionOf(model.TypeString, model.TypeNumber, model.TypeBoolean),
		Required: true, Description: "The value.",
	}
	note := model.Field{
		Name: "note", Type: unionOf(model.TypeString, model.TypeBoolean), Required: false, Description: "",
	}
	count := model.Field{
		Name: "count", Type: unionOf(model.TypeInteger, model.TypeString), Required: true, Description: "",
	}
	described := model.Field{
		Name: "described", Type: refTo("Settings"), Required: false, Description: "The described settings.",
	}

	api := &model.API{
		Title: "T", Version: descriptionVersion(), Tags: nil, Operations: nil, Error: "ErrorResponse",
		Schemas: []model.Schema{
			objectSchema("Settings", "The settings."),
			objectSchema("Widget", "", value, note, count, described),
			objectSchema("ErrorResponse", ""),
		},
	}

	files, err := golang.New().Render(api, options())
	if err != nil {
		t.Fatalf("render: %v", err)
	}

	models := fileText(t, files, "models.go")

	for _, want := range []string{
		"// WidgetValue holds a string, a number or a boolean.\ntype WidgetValue json.RawMessage",
		"// WidgetNote holds a string or a boolean.\ntype WidgetNote json.RawMessage",
		"// WidgetCount holds an integer or a string.\ntype WidgetCount json.RawMessage",
		`case "string", "number", "boolean":`,
		`case "string", "boolean":`,
		`case "number", "string":`,
		`if kind == "number" && !jsonInteger(data) {`,
		"func jsonInteger(data []byte) bool {",
		`return fmt.Errorf("want a string, a number or a boolean, got %s", kind)`,
		"// The value.\n\tValue WidgetValue",
		"Note  *WidgetNote",
		"// The described settings.\n\tDescribed *Settings",
		"// The settings.\ntype Settings struct",
	} {
		if !strings.Contains(models, want) {
			t.Errorf("models.go does not hold %q", want)
		}
	}

	if strings.Contains(models, "// The settings.\n\tDescribed") {
		t.Error("the description of the type of the field wins over the description of the field")
	}
}

// fileText returns the content of one rendered file.
func fileText(t *testing.T, files []clientgen.File, path string) string {
	t.Helper()

	for _, f := range files {
		if f.Path == path {
			return string(f.Content)
		}
	}

	t.Fatalf("the run gave no file %s", path)

	return ""
}

// declaredNames returns the names of the parameters and of the variables of
// the short declarations in the generated files.
func declaredNames(t *testing.T, files []clientgen.File) map[string]bool {
	t.Helper()

	names := map[string]bool{}

	for _, f := range files {
		parsed, err := parser.ParseFile(token.NewFileSet(), f.Path, f.Content, 0)
		if err != nil {
			t.Fatalf("%s: Go cannot read the output: %v", f.Path, err)
		}

		ast.Inspect(parsed, func(n ast.Node) bool {
			collectDeclared(n, names)

			return true
		})
	}

	return names
}

// collectDeclared adds the names that one node declares.
func collectDeclared(n ast.Node, names map[string]bool) {
	switch n := n.(type) {
	case *ast.FuncType:
		for _, p := range n.Params.List {
			for _, id := range p.Names {
				names[id.Name] = true
			}
		}
	case *ast.AssignStmt:
		if n.Tok != token.DEFINE {
			return
		}

		for _, lhs := range n.Lhs {
			if id, ok := lhs.(*ast.Ident); ok {
				names[id.Name] = true
			}
		}
	default:
	}
}

// TestRenderRenamesPathParametersThatHideNames checks that a path parameter
// never hides a name that the generated code uses: the Go keywords, the names
// of the universe scope (nil, true, string), the imported packages and the
// package-level names of the hand-written files.
func TestRenderRenamesPathParametersThatHideNames(t *testing.T) {
	t.Parallel()

	for _, name := range []string{
		"http", "nil", "true", "false", "string", "len", "error", "json", "context", "finish", "request", "type",
		"call", "message", "func",
	} {
		t.Run(name, func(t *testing.T) {
			t.Parallel()

			api := hostileModel()
			api.Operations[0].Path = "/api/dustpan/v1/things/{" + name + "}"
			api.Operations[0].Parameters[0].Name = name

			files, err := golang.New().Render(api, options())
			if err != nil {
				t.Fatalf("render: %v", err)
			}

			if declaredNames(t, files)[name] {
				t.Errorf("a parameter of the generated code is named %s", name)
			}
		})
	}
}

// snake writes the name of a package-level identifier as a path parameter:
// newKey gives new_key.
func snake(name string) string {
	var b strings.Builder

	for _, r := range name {
		if r >= 'A' && r <= 'Z' {
			b.WriteByte('_')
			r += 'a' - 'A'
		}

		b.WriteRune(r)
	}

	return b.String()
}

// TestReservedNamesFollowTheHandWrittenFiles reads the transport and the
// adapter loop, and checks that no package-level name of them can be taken by
// a schema, a query type or a path parameter. The names come from the files,
// so the lists cannot drift from them.
func TestReservedNamesFollowTheHandWrittenFiles(t *testing.T) {
	t.Parallel()

	for _, file := range []string{"transport.go.txt", "main.go.txt"} {
		path := filepath.Join("..", "conformance", "goclient", "files", file)

		src, err := os.ReadFile(path) //nolint:gosec // G304: the path is fixed in this test.
		if err != nil {
			t.Fatalf("read %s: %v", file, err)
		}

		parsed, err := parser.ParseFile(token.NewFileSet(), file, src, 0)
		if err != nil {
			t.Fatalf("parse %s: %v", file, err)
		}

		for _, name := range packageLevelNames(parsed) {
			switch {
			case token.IsExported(name) && file == "transport.go.txt":
				checkSchemaRefused(t, name)
			case token.IsExported(name):
			default:
				checkParameterRenamed(t, name)
			}
		}
	}
}

// checkSchemaRefused checks that a schema with the name of the transport is
// refused.
func checkSchemaRefused(t *testing.T, name string) {
	t.Helper()

	api := hostileModel()
	api.Schemas[0].Name = name

	if _, err := golang.New().Render(api, options()); !errors.Is(err, clientgen.ErrInvalidName) {
		t.Errorf("schema %s: want ErrInvalidName, got %v", name, err)
	}
}

// checkParameterRenamed checks that a path parameter with the name of a
// package-level name does not give a parameter with that name.
func checkParameterRenamed(t *testing.T, name string) {
	t.Helper()

	param := snake(name)
	api := hostileModel()
	api.Operations[0].Path = "/api/dustpan/v1/things/{" + param + "}"
	api.Operations[0].Parameters[0].Name = param

	files, err := golang.New().Render(api, options())
	if err != nil {
		t.Errorf("path parameter %s: %v", param, err)

		return
	}

	if declaredNames(t, files)[name] {
		t.Errorf("path parameter %s: a parameter of the generated code is named %s", param, name)
	}
}

// packageLevelNames returns the names of the functions, types, constants and
// variables that a file declares at package level.
func packageLevelNames(f *ast.File) []string {
	var names []string

	for _, decl := range f.Decls {
		switch d := decl.(type) {
		case *ast.FuncDecl:
			if d.Recv == nil {
				names = append(names, d.Name.Name)
			}
		case *ast.GenDecl:
			names = append(names, specNames(d.Specs)...)
		default:
		}
	}

	return names
}

// specNames returns the names that type, constant and variable specs declare.
func specNames(specs []ast.Spec) []string {
	var names []string

	for _, spec := range specs {
		switch sp := spec.(type) {
		case *ast.TypeSpec:
			names = append(names, sp.Name.Name)
		case *ast.ValueSpec:
			for _, id := range sp.Names {
				names = append(names, id.Name)
			}
		default:
		}
	}

	return names
}

// TestIsGeneratedReadsTheFirstLineOnly checks that a file is generated only when
// its first line is the header. A hand-written file that quotes the header
// must stay, because the writer deletes the files that it calls generated.
func TestIsGeneratedReadsTheFirstLineOnly(t *testing.T) {
	t.Parallel()

	const header = "// Code generated by clientgen 0.1.0 from API description 0.0.0. DO NOT EDIT."

	tests := []struct {
		name string
		head string
		want bool
	}{
		{"header on the first line", header + "\npackage x\n", true},
		{"header with a carriage return", header + "\r\npackage x\n", true},
		{"header alone", header, true},
		{"header on a later line", "package x\n" + header + "\n", false},
		{"header after a blank line", "\n" + header + "\n", false},
		{"header after a byte order mark", "\ufeff" + header + "\n", false},
		{"header in a doc comment", "// Package x quotes:\n// " + header + "\npackage x\n", false},
		{"header with text after it", header + " and more\npackage x\n", false},
		{"other generator", "// Code generated by protoc-gen-go. DO NOT EDIT.\n", false},
		{"empty file", "", false},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			if got := golang.New().IsGenerated([]byte(tt.head)); got != tt.want {
				t.Errorf("IsGenerated(%q) = %v, want %v", tt.head, got, tt.want)
			}
		})
	}
}

// TestOwnsNoPath checks that the Go client owns no path: its package and the
// directory of its adapter hold hand-written files too.
func TestOwnsNoPath(t *testing.T) {
	t.Parallel()

	for _, path := range []string{"models.go", "transport.go", "cmd/conformance-adapter/main.go"} {
		if golang.New().Owned(path) {
			t.Errorf("Owned(%q) = true, want false", path)
		}
	}
}
