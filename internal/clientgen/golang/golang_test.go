// updateGolden rewrites the golden files:
//
//	go test ./internal/clientgen/golang -run TestRenderGolden -update
//
//nolint:gochecknoglobals // A test flag is read once; passing it as a parameter adds nothing.
var updateGolden = flag.Bool("update", false, "write the golden files of the Go template set")

// descriptionPath is the published description, from this package.
const descriptionPath = "../../api/apidesc/openapi.json"

func coveredOperations() []string {
	return []string{
		"createProfile", "createProfileRevision", "getCapabilities", "getNotificationSink",
		"getPreferences", "getProfile", "listNotificationSinks", "putGitHostApp",
	}
}

// options returns the options of a client for the checked-in description. The
// client version takes its major and minor parts from the description, so a
// change of the description version does not need a change here.
func options() clientgen.Options {
	version, err := clientgen.ClientVersion(descriptionVersion(), 0)
	if err != nil {
		panic(err)
	}

	return clientgen.Options{
		Package: "opendustpan.org/client", ClientVersion: version, ServerRelease: "0.1.0-test",
		ServerCommit: "development", Description: nil,
		GeneratorVersion: clientgen.GeneratorVersion, DescriptionSHA256: "",
	}
}

// descriptionVersion returns info.version of the checked-in description. It
// panics when the file does not read, because a test cannot go on without it.
func descriptionVersion() string {
	raw, err := os.ReadFile(descriptionPath)
	if err != nil {
		panic(err)
	}

	api, err := clientgen.NewParser(coveredOperations()...).Parse(raw)
	if err != nil {
		panic(err)
	}

	return api.Version
}

func publishedModel(t *testing.T) *model.API {
	t.Helper()

	raw, err := os.ReadFile(descriptionPath)
	if err != nil {
		t.Fatalf("read the description: %v", err)
	}

	api, err := clientgen.NewParser(coveredOperations()...).Parse(raw)
	if err != nil {
		t.Fatalf("parse the description: %v", err)
	}

	return api
}

// TestRenderIsDeterministic runs the generator twice on the same input and
// compares the bytes.
func TestRenderIsDeterministic(t *testing.T) {
	t.Parallel()

	api := publishedModel(t)

	first, err := golang.New().Render(api, options())
	if err != nil {
		t.Fatalf("render: %v", err)
	}

	second, err := golang.New().Render(publishedModel(t), options())
	if err != nil {
		t.Fatalf("render again: %v", err)
	}

	if len(first) != len(second) {
		t.Fatalf("the runs give %d and %d files", len(first), len(second))
	}

	for i := range first {
		if first[i].Path != second[i].Path || !bytes.Equal(first[i].Content, second[i].Content) {
			t.Errorf("file %s differs between two runs", first[i].Path)
		}
	}
}

// TestRenderGolden compares the output with the golden files.
func TestRenderGolden(t *testing.T) {
	t.Parallel()

	files, err := golang.New().Render(publishedModel(t), options())
	if err != nil {
		t.Fatalf("render: %v", err)
	}

	if len(files) == 0 {
		t.Fatal("no file")
	}

	for _, f := range files {
		golden := filepath.Join("testdata", "golden", filepath.FromSlash(f.Path)+".golden")

		if *updateGolden {
			if mkErr := os.MkdirAll(filepath.Dir(golden), 0o750); mkErr != nil {
				t.Fatal(mkErr)
			}

			if wErr := os.WriteFile(golden, f.Content, 0o600); wErr != nil {
				t.Fatal(wErr)
			}

			continue
		}

		want := readGolden(t, golden)

		if !bytes.Equal(want, f.Content) {
			t.Errorf(
				"%s differs from %s: run go test ./internal/clientgen/golang -run TestRenderGolden -update",
				f.Path,
				golden,
			)
		}
	}
}

// readGolden reads a golden file.
func readGolden(t *testing.T, name string) []byte {
	t.Helper()

	want, err := os.ReadFile(name) //nolint:gosec // The name is under testdata.
	if err != nil {
		t.Fatalf("read %s: %v", name, err)
	}

	return want
}

func TestRenderFilesAreInOrderWithHeaders(t *testing.T) {
	t.Parallel()

	files, err := golang.New().Render(publishedModel(t), options())
	if err != nil {
		t.Fatalf("render: %v", err)
	}

	for i, f := range files {
		if i > 0 && files[i-1].Path >= f.Path {
			t.Errorf("paths are not in order: %s before %s", files[i-1].Path, f.Path)
		}

		first, _, _ := strings.Cut(string(f.Content), "\n")
		if !strings.HasPrefix(first, "// Code generated by clientgen ") || !strings.HasSuffix(first, " DO NOT EDIT.") {
			t.Errorf("%s: the header is %q", f.Path, first)
		}

		if !strings.Contains(first, "API description "+descriptionVersion()) {
			t.Errorf("%s: the header does not name the description version: %q", f.Path, first)
		}
	}
}

// hostileText is text that tries to leave a comment or a string, and holds
// the characters that a person cannot see.
func hostileText() string {
	return "x\n}\nfunc evil() {}\n// " + string(rune(0x2028)) + "func evil2() {} /* */ \"` \x00 " + string(rune(0x202e))
}

// controlChars are the characters that must not be in a comment: a null, a
// line separator and a right-to-left override.
func controlChars() string {
	return "\x00" + string(rune(0x2028)) + string(rune(0x202e))
}

func typ(kind model.TypeKind) model.Type {
	return model.Type{Kind: kind, Format: "", Elem: nil, Ref: "", Const: "", Nullable: false, Members: nil}
}

// unionOf makes the type of a list of primitive type names.
func unionOf(kinds ...model.TypeKind) model.Type {
	t := typ(model.TypeUnion)
	t.Members = kinds

	return t
}

func refTo(name string) model.Type {
	t := typ(model.TypeRef)
	t.Ref = name

	return t
}

func objectSchema(name, doc string, fields ...model.Field) model.Schema {
	return model.Schema{
		Name: name, Kind: model.KindObject, Description: doc, Fields: fields, Values: nil, Open: false, Extra: nil,
		Discriminator: "", Variants: nil, Base: "", Union: "",
	}
}

func enumSchema(name string, values ...string) model.Schema {
	return model.Schema{
		Name: name, Kind: model.KindEnum, Description: "", Fields: nil, Values: values, Open: false, Extra: nil,
		Discriminator: "", Variants: nil, Base: "", Union: "",
	}
}

// hostileModel is a model with hostile text in each place that reaches a
// comment.
func hostileModel() *model.API {
	evil := hostileText()

	param := model.Parameter{
		Name: "thing_id", In: model.InPath, Required: true, Type: typ(model.TypeString), Description: evil,
	}

	result := refTo("Thing")

	op := model.Operation{
		ID: "getThing", Method: model.MethodGet, Path: "/api/dustpan/v1/things/{thing_id}",
		Tags: nil, Summary: evil, Description: evil, Actions: []string{"unit:read"}, Public: false,
		Parameters: []model.Parameter{param}, Body: nil,
		Result:         model.Response{Statuses: []int{200}, Type: &result, ETag: false},
		IdempotencyKey: false, IfMatch: model.IfMatchNone, Page: nil,
	}

	name := model.Field{Name: "name", Type: typ(model.TypeString), Required: true, Description: evil}

	return &model.API{
		Title: evil, Version: descriptionVersion(), Tags: nil, Operations: []model.Operation{op},
		Error:   "ErrorResponse",
		Schemas: []model.Schema{objectSchema("Thing", evil, name), objectSchema("ErrorResponse", "")},
	}
}

// TestRenderKeepsHostileTextInComments checks that text from the description
// cannot add code to the output: Go reads the file, and finds no function the
// description added.
func TestRenderKeepsHostileTextInComments(t *testing.T) {
	t.Parallel()

	files, err := golang.New().Render(hostileModel(), options())
	if err != nil {
		t.Fatalf("render: %v", err)
	}

	for _, f := range files {
		parsed, parseErr := parser.ParseFile(token.NewFileSet(), f.Path, f.Content, parser.ParseComments)
		if parseErr != nil {
			t.Fatalf("%s: Go cannot read the output: %v", f.Path, parseErr)
		}

		ast.Inspect(parsed, func(n ast.Node) bool {
			if fn, ok := n.(*ast.FuncDecl); ok && strings.HasPrefix(fn.Name.Name, "evil") {
				t.Errorf("%s: the text added the function %s", f.Path, fn.Name.Name)
			}

			return true
		})

		for _, c := range parsed.Comments {
			if strings.ContainsAny(c.Text(), controlChars()) {
				t.Errorf("%s: a comment holds a control character: %q", f.Path, c.Text())
			}
		}
	}
}

