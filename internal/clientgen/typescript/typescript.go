// Package typescript is the template set of the TypeScript client. It turns
// the model of an API description into one npm package: the types, a runtime
// validator for every schema, the table of operations, a typed client and a
// default transport that uses the global fetch.
//
// The package has no dependency. The generator writes all of it, also the
// runtime files that no description changes (the combinators of the
// validators, the transport interface and the default transport). They are
// embedded in this package, so that a checked-in package and a fresh run give
// the same bytes, and so that someone who has only the description gets a
// complete package.
package typescript

import (
	"bytes"
	"embed"
	"fmt"
	"io/fs"
	"regexp"
	"slices"
	"strings"
	"text/template"

	"opendustpan.org/opendustpan/internal/clientgen"
	"opendustpan.org/opendustpan/internal/clientgen/model"
)

//go:embed templates/*.tmpl
var templateFS embed.FS

//go:embed runtime/*.ts
var runtimeFS embed.FS

// packageName is the shape of the name of an npm package in a scope.
var packageName = regexp.MustCompile(`^@[a-z0-9][a-z0-9-]*/[a-z0-9][a-z0-9-]*$`)

// The paths of the files, relative to the package directory.
const (
	pathPackage  = "package.json"
	pathTSConfig = "tsconfig.json"
	srcDir       = "src/"
)

// language is the TypeScript template set.
type language struct{}

// New returns the TypeScript template set.
func New() clientgen.Language { //nolint:ireturn // The port is the contract; callers do not depend on the type.
	return language{}
}

// Name implements clientgen.Language.
func (language) Name() string { return "typescript" }

// Render implements clientgen.Language. The files are in the order of their
// paths.
func (language) Render(api *model.API, opts clientgen.Options) ([]clientgen.File, error) {
	runtime, err := runtimeSources()
	if err != nil {
		return nil, err
	}

	d, err := newData(api, opts, runtime)
	if err != nil {
		return nil, err
	}

	tmpl, err := template.New("typescript").Funcs(funcs()).ParseFS(templateFS, "templates/*.tmpl")
	if err != nil {
		return nil, fmt.Errorf("typescript templates: %w", err)
	}

	outputs := []struct{ path, template string }{
		{pathPackage, "package.json.tmpl"},
		{pathTSConfig, "tsconfig.json.tmpl"},
		{srcDir + "client.ts", "client.ts.tmpl"},
		{srcDir + "decoders.ts", "decoders.ts.tmpl"},
		{srcDir + "index.ts", "index.ts.tmpl"},
		{srcDir + "metadata.ts", "metadata.ts.tmpl"},
		{srcDir + "operations.ts", "operations.ts.tmpl"},
		{srcDir + "types.ts", "types.ts.tmpl"},
	}

	files := make([]clientgen.File, 0, len(outputs)+len(runtime))

	for _, out := range outputs {
		var buf bytes.Buffer
		if err = tmpl.ExecuteTemplate(&buf, out.template, d); err != nil {
			return nil, fmt.Errorf("typescript template %s: %w", out.template, err)
		}

		files = append(files, clientgen.File{Path: out.path, Content: buf.Bytes()})
	}

	for name, src := range runtime {
		content := []byte(d.Header + "\n\n")
		content = append(content, src...)
		files = append(files, clientgen.File{Path: srcDir + name, Content: content})
	}

	slices.SortFunc(files, func(a, b clientgen.File) int { return strings.Compare(a.Path, b.Path) })

	return files, nil
}

// runtimeSources reads the embedded runtime files, by file name.
func runtimeSources() (map[string][]byte, error) {
	entries, err := fs.ReadDir(runtimeFS, "runtime")
	if err != nil {
		return nil, fmt.Errorf("typescript runtime: %w", err)
	}

	sources := make(map[string][]byte, len(entries))

	for _, e := range entries {
		src, readErr := runtimeFS.ReadFile("runtime/" + e.Name())
		if readErr != nil {
			return nil, fmt.Errorf("typescript runtime %s: %w", e.Name(), readErr)
		}

		sources[e.Name()] = src
	}

	return sources, nil
}

// The header of a generated file is the first line of a source file, and the
// first member of package.json, which has no comments. Both carry the name of
// the generator, so that the generated files of other tools do not match.
// It must come first: a hand-written file that quotes the header on a later
// line is not generated, and the writer must not delete it.
var (
	sourceHeader = regexp.MustCompile(
		`\A// Code generated by clientgen \S+ from API description \S+\. DO NOT EDIT\.\r?(?:\n|\z)`,
	)
	jsonHeader = regexp.MustCompile(
		`\A\{\s*"//":\s*"Code generated by clientgen \S+ from API description \S+\. DO NOT EDIT\."`,
	)
)

// header writes the header line of a source file.
func header(generatorVersion, descriptionVersion string) string {
	return "// Code generated by clientgen " + generatorVersion + " from API description " +
		descriptionVersion + ". DO NOT EDIT."
}

// Header implements clientgen.Language.
func (language) Header(opts clientgen.Options, descriptionVersion string) string {
	return header(opts.GeneratorVersion, descriptionVersion)
}

// IsGenerated implements clientgen.Language.
func (language) IsGenerated(head []byte) bool {
	return sourceHeader.Match(head) || jsonHeader.Match(head)
}

// funcs are the encoders that a template calls. A value from the description
// goes into source through one of them only.
func funcs() template.FuncMap {
	return template.FuncMap{
		"tsString": tsString,
		"jsdoc":    jsdoc,
		"propName": propName,
		"join":     strings.Join,
	}
}

// data is what the templates read.
type data struct {
	// Header is the first line of each generated source file.
	Header string
	// Package is the npm name of the package.
	Package            string
	ClientVersion      string
	DescriptionVersion string
	DescriptionSHA256  string
	ServerRelease      string
	GeneratorVersion   string
	Title              string
	Types              []typeView
	Operations         []operationView
}

// newData checks the options, and builds the views of the model.
func newData(api *model.API, opts clientgen.Options, runtime map[string][]byte) (*data, error) {
	if !packageName.MatchString(opts.Package) {
		return nil, fmt.Errorf("%w: package %q is not a scoped npm name", clientgen.ErrInvalidName, opts.Package)
	}

	tokens := []struct{ what, value string }{
		{"description version", api.Version},
		{"client version", opts.ClientVersion},
		{"server release", opts.ServerRelease},
		{"generator version", opts.GeneratorVersion},
	}

	for _, tok := range tokens {
		if err := clientgen.CheckToken(tok.what, tok.value); err != nil {
			return nil, err
		}
	}

	if !sha256Pattern.MatchString(opts.DescriptionSHA256) {
		return nil, fmt.Errorf("%w: description digest %q", clientgen.ErrInvalidName, opts.DescriptionSHA256)
	}

	if err := clientgen.CheckClientVersion(api.Version, opts.ClientVersion); err != nil {
		return nil, err
	}

	if err := clientgen.CheckModel(api); err != nil {
		return nil, err
	}

	d := new(data)
	d.Header = header(opts.GeneratorVersion, api.Version)
	d.Package, d.Title = opts.Package, api.Title
	d.ClientVersion, d.DescriptionVersion = opts.ClientVersion, api.Version
	d.DescriptionSHA256, d.ServerRelease, d.GeneratorVersion = opts.DescriptionSHA256, opts.ServerRelease, opts.GeneratorVersion

	seen := make(map[string]string)

	for _, name := range append(runtimeExports(runtime), globalTypes()...) {
		seen[name] = "the runtime of the package"
	}

	if err := d.addTypes(api, seen); err != nil {
		return nil, err
	}

	if err := d.addOperations(api, seen); err != nil {
		return nil, err
	}

	return d, nil
}

// sha256Pattern is the shape of a SHA-256 digest in lowercase hexadecimal.
var sha256Pattern = regexp.MustCompile(`^[0-9a-f]{64}$`)
