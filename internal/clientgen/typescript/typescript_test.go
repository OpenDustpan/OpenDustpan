// mustWrite writes a file of a test, and makes its directory.
func mustWrite(t *testing.T, dir, name, content string) {
	t.Helper()

	path := filepath.Join(dir, filepath.FromSlash(name))

	if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
		t.Fatal(err)
	}

	if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
		t.Fatal(err)
	}
}

// TestWriterWritesWhatDiffAccepts writes the output, and checks that Diff
// sees no difference, and then sees each kind of difference.
func TestWriterWritesWhatDiffAccepts(t *testing.T) {
	t.Parallel()

	files := render(t, synthetic(t))
	lang := typescript.New()
	dir := t.TempDir()
	generated := string(files[len(files)-1].Content)

	if err := clientgen.NewWriter(lang).Write(dir, files); err != nil {
		t.Fatalf("write: %v", err)
	}

	diffs, err := clientgen.Diff(lang, dir, files)
	if err != nil || len(diffs) != 0 {
		t.Fatalf("a fresh write: want no difference, got %v %v", diffs, err)
	}

	// The compiled files of a build keep the header of their source, and are
	// not the business of the generator. A file without a header is not
	// either.
	mustWrite(t, dir, "dist/x.js", generated)
	mustWrite(t, dir, "node_modules/x.js", generated)
	mustWrite(t, dir, "README.md", "by hand")

	// A stale file, a file with other content and a file that is gone.
	mustWrite(t, dir, "src/old.ts", generated)
	mustWrite(t, dir, "src/types.ts", "// Code generated by clientgen 0.1.0 from API description 0.3.0. DO NOT EDIT.\n")

	if err = os.Remove(filepath.Join(dir, "src", "client.ts")); err != nil {
		t.Fatal(err)
	}

	diffs, err = clientgen.Diff(lang, dir, files)
	if err != nil {
		t.Fatalf("diff: %v", err)
	}

	want := []string{"differs: src/types.ts", "missing: src/client.ts", "stale: src/old.ts"}
	if !slices.Equal(diffs, want) {
		t.Errorf("want %v, got %v", want, diffs)
	}

	// Write puts it right, removes the stale file, and keeps the other files.
	if err = clientgen.NewWriter(lang).Write(dir, files); err != nil {
		t.Fatalf("write again: %v", err)
	}

	if diffs, err = clientgen.Diff(lang, dir, files); err != nil || len(diffs) != 0 {
		t.Errorf("after the second write: want no difference, got %v %v", diffs, err)
	}

	for _, kept := range []string{"README.md", "dist/x.js", "node_modules/x.js"} {
		if _, err = os.Stat(filepath.Join(dir, filepath.FromSlash(kept))); err != nil {
			t.Errorf("%s is gone: %v", kept, err)
		}
	}
}

