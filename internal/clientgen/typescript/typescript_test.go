// updateGolden rewrites the golden files:
//
//	go test ./internal/clientgen/typescript -run TestRenderGolden -update
//
//nolint:gochecknoglobals // A test flag is read once; passing it as a parameter adds nothing.
var updateGolden = flag.Bool("update", false, "write the golden files of the TypeScript template set")

// commit is a server commit that the tests use.
const commit = "0123456789abcdef0123456789abcdef01234567"

// syntheticBytes are the bytes of the synthetic description.
func syntheticBytes() []byte {
	raw, err := os.ReadFile("testdata/synthetic.json")
	if err != nil {
		panic(err)
	}

	return raw
}

// digest is the SHA-256 digest of the synthetic description.
func digest() string {
	sum := sha256.Sum256(syntheticBytes())

	return hex.EncodeToString(sum[:])
}

func options(version string) clientgen.Options {
	return clientgen.Options{
		Package: "@opendustpan/client", ClientVersion: version, ServerRelease: "0.1.0-test",
		ServerCommit: commit, Description: syntheticBytes(),
		GeneratorVersion: clientgen.GeneratorVersion, DescriptionSHA256: digest(),
	}
}

func synthetic(t *testing.T) *model.API {
	t.Helper()

	raw, err := os.ReadFile("testdata/synthetic.json")
	if err != nil {
		t.Fatalf("read the description: %v", err)
	}

	api, err := clientgen.NewParser().Parse(raw)
	if err != nil {
		t.Fatalf("parse the description: %v", err)
	}

	return api
}

func render(t *testing.T, api *model.API) []clientgen.File {
	t.Helper()

	files, err := typescript.New().Render(api, options(api.Version))
	if err != nil {
		t.Fatalf("render: %v", err)
	}

	return files
}

// runtimeFiles are the files that the template set copies from its runtime
// directory. The golden files hold the others, which depend on the description.
func runtimeFiles(t *testing.T) []string {
	t.Helper()

	entries, err := os.ReadDir("runtime")
	if err != nil {
		t.Fatalf("read the runtime directory: %v", err)
	}

	names := make([]string, 0, len(entries))
	for _, e := range entries {
		names = append(names, "src/"+e.Name())
	}

	return names
}

func TestRenderIsDeterministic(t *testing.T) {
	t.Parallel()

	first, second := render(t, synthetic(t)), render(t, synthetic(t))
	if len(first) != len(second) {
		t.Fatalf("the runs give %d and %d files", len(first), len(second))
	}

	for i := range first {
		if first[i].Path != second[i].Path || !bytes.Equal(first[i].Content, second[i].Content) {
			t.Errorf("file %s differs between two runs", first[i].Path)
		}
	}
}

func TestFilesAreInTheOrderOfTheirPaths(t *testing.T) {
	t.Parallel()

	files := render(t, synthetic(t))
	paths := make([]string, len(files))

	for i, f := range files {
		paths[i] = f.Path
	}

	if !slices.IsSorted(paths) {
		t.Errorf("the paths are not sorted: %v", paths)
	}
}

// TestRenderGolden compares the files that depend on the description with the
// golden files.
func TestRenderGolden(t *testing.T) {
	t.Parallel()

	skip := runtimeFiles(t)

	for _, f := range render(t, synthetic(t)) {
		if slices.Contains(skip, f.Path) {
			continue
		}

		golden := filepath.Join("testdata", "golden", filepath.FromSlash(f.Path)+".golden")

		if *updateGolden {
			if err := os.MkdirAll(filepath.Dir(golden), 0o750); err != nil {
				t.Fatalf("make the golden directory: %v", err)
			}

			if err := os.WriteFile(golden, f.Content, 0o600); err != nil {
				t.Fatalf("write %s: %v", golden, err)
			}

			continue
		}

		want, err := os.ReadFile(golden) //nolint:gosec // The name is under testdata.
		if err != nil {
			t.Fatalf("read %s: %v", golden, err)
		}

		if !bytes.Equal(want, f.Content) {
			t.Errorf("%s differs from %s; run the test with -update and review the diff", f.Path, golden)
		}
	}
}

// TestRuntimeFilesAreCopiedWithTheHeader checks that the runtime files go
// into the output as they are, below the header.
func TestRuntimeFilesAreCopiedWithTheHeader(t *testing.T) {
	t.Parallel()

	api := synthetic(t)
	files := render(t, api)
	head := "// Code generated by clientgen " + clientgen.GeneratorVersion + " from API description " + api.Version +
		". DO NOT EDIT.\n\n"

	for _, path := range runtimeFiles(t) {
		src, err := os.ReadFile(strings.Replace(path, "src/", "runtime/", 1))
		if err != nil {
			t.Fatalf("read %s: %v", path, err)
		}

		i := slices.IndexFunc(files, func(f clientgen.File) bool { return f.Path == path })
		if i < 0 {
			t.Errorf("%s is not in the output", path)

			continue
		}

		if string(files[i].Content) != head+string(src) {
			t.Errorf("%s is not the header and the runtime file", path)
		}
	}
}

// TestTwoSuccessStatusesAreInTheTable is the golden case of an operation that
// answers with two success statuses: the table holds both and no other.
func TestTwoSuccessStatusesAreInTheTable(t *testing.T) {
	t.Parallel()

	statuses := map[string]string{
		"putWidgetSettings": "statuses: [200, 201],",
		"startWidgetJob":    "statuses: [202],",
		"ping":              "statuses: [204],",
		"getWidgetLabels":   "statuses: [200],",
	}

	var table string

	for _, f := range render(t, synthetic(t)) {
		if f.Path == "src/operations.ts" {
			table = string(f.Content)
		}
	}

	for op, want := range statuses {
		start := strings.Index(table, "  "+op+": operation<")
		if start < 0 {
			t.Fatalf("operation %s is not in the table", op)
		}

		end := strings.Index(table[start:], "\n  ),\n")
		if !strings.Contains(table[start:start+end], want) {
			t.Errorf("operation %s: want %q in its entry", op, want)
		}
	}
}

// TestTextFromTheDescriptionCannotEndAComment checks that "*/" in a title, a
// summary or a schema description does not end a JSDoc comment early.
func TestTextFromTheDescriptionCannotEndAComment(t *testing.T) {
	t.Parallel()

	for _, f := range render(t, synthetic(t)) {
		for line := range strings.SplitSeq(string(f.Content), "\n") {
			trimmed := strings.TrimSpace(line)
			if strings.HasPrefix(trimmed, "*") && !strings.HasPrefix(trimmed, "*/") && strings.Contains(trimmed, "*/") {
				t.Errorf("%s: a comment line ends the comment early: %q", f.Path, line)
			}

			if strings.Contains(line, "/** ") && strings.Contains(strings.TrimSuffix(line, " */"), "*/") {
				t.Errorf("%s: a one-line comment ends early: %q", f.Path, line)
			}
		}
	}
}

func TestHeaders(t *testing.T) {
	t.Parallel()

	lang := typescript.New()

	files := render(t, synthetic(t))
	for _, f := range files {
		if !lang.IsGenerated(f.Content) {
			t.Errorf("%s has no header that IsGenerated knows", f.Path)
		}
	}

	hostile := map[string]string{
		"a header on the second line":       "x\n// Code generated by clientgen 0.1.0 from API description 0.3.0. DO NOT EDIT.\n",
		"another generator":                 "// Code generated by protoc-gen-ts. DO NOT EDIT.\n",
		"a header with a suffix":            "// Code generated by clientgen 0.1.0 from API description 0.3.0. DO NOT EDIT. and more\n",
		"a byte order mark":                 "\xef\xbb\xbf// Code generated by clientgen 0.1.0 from API description 0.3.0. DO NOT EDIT.\n",
		"json without the member":           `{"name": "x"}`,
		"json with the member in 2nd place": `{"name": "x", "//": "Code generated by clientgen 0.1.0 from API description 0.3.0. DO NOT EDIT."}`,
		"empty":                             "",
	}

	for name, head := range hostile {
		if lang.IsGenerated([]byte(head)) {
			t.Errorf("%s: IsGenerated says yes", name)
		}
	}
}

var versionOK = regexp.MustCompile(`"version": "0\.3\.0"`)

func TestPackageJSON(t *testing.T) {
	t.Parallel()

	for _, f := range render(t, synthetic(t)) {
		if f.Path != "package.json" {
			continue
		}

		text := string(f.Content)
		if !versionOK.MatchString(text) || !strings.Contains(text, `"name": "@opendustpan/client"`) {
			t.Errorf("package.json: want the name and the version of the description:\n%s", text)
		}

		if strings.Contains(text, "dependencies") {
			t.Errorf("package.json: the package must have no dependency:\n%s", text)
		}
	}
}

