const generatedFile = "// Code generated by clientgen 0.1.0 from API description 0.1.0. DO NOT EDIT.\n\npackage x\n"

func TestWriterRefusesUnsafePaths(t *testing.T) {
	t.Parallel()

	for _, p := range []string{"", "/etc/passwd", "../outside.go", "a/../../outside.go", "a/./b.go", "a//b.go", `a\b.go`, "..", "a/../b.go"} {
		t.Run(p, func(t *testing.T) {
			t.Parallel()

			dir := t.TempDir()

			err := clientgen.NewWriter(golang.New()).Write(dir, []clientgen.File{
				{Path: "ok.go", Content: []byte(generatedFile)},
				{Path: p, Content: []byte(generatedFile)},
			})
			if !errors.Is(err, clientgen.ErrUnsafePath) {
				t.Fatalf("want ErrUnsafePath, got %v", err)
			}

			// A bad path leaves the directory as it was: not even the good file
			// is written.
			if entries, readErr := os.ReadDir(dir); readErr != nil || len(entries) != 0 {
				t.Errorf("the directory should be empty: %v %v", entries, readErr)
			}
		})
	}
}

func TestWriterRefusesTheSamePathTwice(t *testing.T) {
	t.Parallel()

	f := clientgen.File{Path: "a.go", Content: []byte(generatedFile)}

	err := clientgen.NewWriter(golang.New()).Write(t.TempDir(), []clientgen.File{f, f})
	if !errors.Is(err, clientgen.ErrUnsafePath) {
		t.Fatalf("want ErrUnsafePath, got %v", err)
	}
}

// TestWriterContainsASymlink is the layer that does not rely on the path
// check: a link inside the directory that points outside must not be followed.
func TestWriterContainsASymlink(t *testing.T) {
	t.Parallel()

	dir, outside := t.TempDir(), t.TempDir()
	if err := os.Symlink(outside, filepath.Join(dir, "link")); err != nil {
		t.Skipf("no symbolic link: %v", err)
	}

	err := clientgen.NewWriter(golang.New()).
		Write(dir, []clientgen.File{{Path: "link/escape.go", Content: []byte(generatedFile)}})
	if err == nil {
		t.Fatal("the writer followed a link out of the directory")
	}

	if _, statErr := os.Stat(filepath.Join(outside, "escape.go")); statErr == nil {
		t.Fatal("the writer wrote outside the directory")
	}
}

func TestWriterKeepsFilesWithoutHeader(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	transport := filepath.Join(dir, "transport.go")

	if err := os.WriteFile(transport, []byte("package x\n// hand written\n"), 0o600); err != nil {
		t.Fatal(err)
	}

	// A hand-written file is not removed, and it is not overwritten.
	err := clientgen.NewWriter(golang.New()).
		Write(dir, []clientgen.File{{Path: "transport.go", Content: []byte(generatedFile)}})
	if !errors.Is(err, clientgen.ErrNotGenerated) {
		t.Fatalf("want ErrNotGenerated, got %v", err)
	}

	got, readErr := os.ReadFile(transport) //nolint:gosec // The path is in the directory of the test.
	if readErr != nil || string(got) != "package x\n// hand written\n" {
		t.Fatalf("the hand-written file changed: %q %v", got, readErr)
	}

	other := clientgen.File{Path: "other.go", Content: []byte(generatedFile)}

	err = clientgen.NewWriter(golang.New()).Write(dir, []clientgen.File{other})
	if err != nil {
		t.Fatalf("write another file: %v", err)
	}

	if _, statErr := os.Stat(transport); statErr != nil {
		t.Errorf("the hand-written file is gone: %v", statErr)
	}
}

func TestWriterRemovesStaleGeneratedFiles(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	w := clientgen.NewWriter(golang.New())

	first := []clientgen.File{
		{Path: "a.go", Content: []byte(generatedFile)},
		{Path: "sub/b.go", Content: []byte(generatedFile)},
	}
	if err := w.Write(dir, first); err != nil {
		t.Fatalf("first write: %v", err)
	}

	if err := w.Write(dir, first[:1]); err != nil {
		t.Fatalf("second write: %v", err)
	}

	if _, err := os.Stat(filepath.Join(dir, "sub", "b.go")); !errors.Is(err, os.ErrNotExist) {
		t.Errorf("the stale file should be gone: %v", err)
	}

	if _, err := os.Stat(filepath.Join(dir, "a.go")); err != nil {
		t.Errorf("the file of the new run should stay: %v", err)
	}
}

// TestWriterKeepsTheFilesOfOtherGenerators checks that only the header of
// clientgen counts: the output of another generator next to the client stays,
// and it is not replaced.
func TestWriterKeepsTheFilesOfOtherGenerators(t *testing.T) {
	t.Parallel()

	others := map[string]string{
		"x_string.go":   "// Code generated by \"stringer -type=X\"; DO NOT EDIT.\n\npackage x\n",
		"mock_x.go":     "// Code generated by MockGen. DO NOT EDIT.\n\npackage x\n",
		"x.pb.go":       "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage x\n",
		"lookalike.go":  "// Code generated by clientgen 0.1.0 from API description 0.1.0. DO NOT EDIT. extra\n",
		"bin/adapter":   string(make([]byte, 4096)),
		"sub/other.txt": "no header\n",
	}

	dir := t.TempDir()

	for name, content := range others {
		full := filepath.Join(dir, name)
		if err := os.MkdirAll(filepath.Dir(full), 0o750); err != nil {
			t.Fatal(err)
		}

		if err := os.WriteFile(full, []byte(content), 0o600); err != nil {
			t.Fatal(err)
		}
	}

	w := clientgen.NewWriter(golang.New())
	if err := w.Write(dir, []clientgen.File{{Path: "a.go", Content: []byte(generatedFile)}}); err != nil {
		t.Fatalf("write: %v", err)
	}

	for name, content := range others {
		got, err := os.ReadFile(filepath.Join(dir, name)) //nolint:gosec // The path is in the directory of the test.
		if err != nil || string(got) != content {
			t.Errorf("%s changed or is gone: %v", name, err)
		}
	}

	// Writing over a file of another generator is refused.
	err := w.Write(dir, []clientgen.File{{Path: "x_string.go", Content: []byte(generatedFile)}})
	if !errors.Is(err, clientgen.ErrNotGenerated) {
		t.Fatalf("want ErrNotGenerated, got %v", err)
	}
}

// hashLanguage is a language with a header in the form of a hash comment. It
// shows that the writer holds no comment form of its own.
type hashLanguage struct{}

func (hashLanguage) Name() string { return "hash" }

func (hashLanguage) Render(*model.API, clientgen.Options) ([]clientgen.File, error) { return nil, nil }

func (hashLanguage) Header(opts clientgen.Options, descriptionVersion string) string {
	return "# generated by clientgen " + opts.GeneratorVersion + " from " + descriptionVersion
}

func (hashLanguage) IsGenerated(head []byte) bool {
	return bytes.HasPrefix(head, []byte("# generated by clientgen "))
}

func TestWriterUsesTheHeaderOfTheLanguage(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	w := clientgen.NewWriter(hashLanguage{})
	header := hashLanguage{}.Header(
		clientgen.Options{
			Package:           "",
			ClientVersion:     "",
			ServerRelease:     "",
			GeneratorVersion:  "0.1.0",
			DescriptionSHA256: "",
		},
		"0.1.0",
	) + "\n"

	files := []clientgen.File{{Path: "a.py", Content: []byte(header)}, {Path: "b.py", Content: []byte(header)}}
	if err := w.Write(dir, files); err != nil {
		t.Fatalf("first write: %v", err)
	}

	if err := w.Write(dir, files[:1]); err != nil {
		t.Fatalf("second write: %v", err)
	}

	if _, err := os.Stat(filepath.Join(dir, "b.py")); !errors.Is(err, os.ErrNotExist) {
		t.Errorf("the stale file with a hash header should be gone: %v", err)
	}

	// A Go header is not a header of this language.
	if err := os.WriteFile(filepath.Join(dir, "g.go"), []byte(generatedFile), 0o600); err != nil {
		t.Fatal(err)
	}

	if err := w.Write(dir, files[:1]); err != nil {
		t.Fatalf("third write: %v", err)
	}

	if _, err := os.Stat(filepath.Join(dir, "g.go")); err != nil {
		t.Errorf("a Go header file stays for a hash language: %v", err)
	}
}
